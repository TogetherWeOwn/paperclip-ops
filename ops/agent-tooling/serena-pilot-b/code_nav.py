#!/usr/bin/env python3
"""code-nav: Serena-backed symbolic code navigation for builders (Pilot B).

Runs a Serena 2.0.0 MCP server as a child process in the caller's repo, makes
exactly one tool call over stdio, prints the result and exits. No connection,
grant or binding is needed, and there is no per-request tool-schema cost.

Usage (run from anywhere inside the repo to navigate):
  code-nav outline <file> [--depth 1]
  code-nav symbol <name_path> [--body] [--in <file-or-dir>] [--depth 0] [--info]
  code-nav refs <name_path> <file>

Uses PyYAML from the pinned Serena venv. Concurrent calls for the same repo are serialized with a flock
(each call starts a ~1.9 GB language server); the whole operation (queue wait
plus the tool call) is bounded by --timeout (default 120 s).

Nothing is written into the repo: the pilot global config
(serena-config.pilot.yml) redirects Serena's project data folder from the
default $projectDir/.serena to $SERENA_HOME/projects/$projectFolderName.
Without that redirect, the first call in a fresh worktree would create an
untracked .serena/ directory (autogenerated project.yml, .gitignore, LS
caches) inside the repo.
"""
import argparse
import fcntl
import hashlib
import json
import os
import signal
import stat
import subprocess
import sys
import tempfile

import yaml

DEFAULT_TIMEOUT_S = 120
MCP_PROTOCOL_VERSION = "2024-11-05"

# Verified against the serena-agent 2.0.0 sdist (src layout, cli.py,
# tools/symbol_tools.py, config/serena_config.py, solidlsp/). Do not change
# these from memory; re-verify against the pinned sdist instead.
SERENA_ARGV_TAIL = [
    "start-mcp-server",
    "--transport", "stdio",
    # --context takes a built-in name or a path to a custom context YAML.
    "--context", "@CONTEXT@",
    # Resolves the nearest ancestor with .serena/project.yml or .git; the
    # .git check accepts worktree pointer files, so builder worktrees work.
    "--project-from-cwd",
    # 2.0.0 defaults to the REPL interface, where tool filtering does NOT
    # apply. Without this the 3-tool allowlist silently fails.
    "--agent-interface", "tools",
    # Excludes memory/onboarding tools, preserving "wrote nothing".
    "--mode", "no-memories",
    # Dashboard defaults to enabled+open; both must be off headless.
    # (gui-log-window already defaults to false, so it is not passed.)
    "--enable-web-dashboard", "false",
    "--open-web-dashboard", "false",
]


def die(msg, code=1):
    sys.stderr.write("code-nav: %s\n" % msg)
    sys.exit(code)


class _Timeout(Exception):
    pass


def _on_alarm(signum, frame):
    raise _Timeout()


def _opt_paths():
    """Install locations. Overridable for testing; production layout is:
    $OPT/venv, $OPT/code_nav.py, $OPT/builder-readonly.yml,
    $OPT/serena-config.pilot.yml, with a sh shim at /paperclip/.local/bin/code-nav.
    """
    opt = os.environ.get("SERENA_OPT_DIR") or os.path.dirname(os.path.abspath(__file__))
    venv = os.environ.get("SERENA_VENV") or os.path.join(opt, "venv")
    return {
        "serena_bin": os.path.join(venv, "bin", "serena"),
        "context": os.environ.get("SERENA_CONTEXT") or os.path.join(opt, "builder-readonly.yml"),
        "config_template": os.path.join(opt, "serena-config.pilot.yml"),
    }


def _repo_root():
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"],
            capture_output=True, text=True, check=True,
        ).stdout.strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        die("not inside a git checkout (run from the repo to navigate)", code=2)
    return os.path.realpath(out)


def _to_root_rel(root, user_path, kind="path"):
    """Resolve a cwd-relative, root-relative or absolute path to a
    root-relative posix path. Relative paths try the cwd first, then the repo
    root (agents call from subdirectories with root-relative paths); an
    existing cwd interpretation always wins, so there is no ambiguity."""
    if os.path.isabs(user_path):
        cands = [user_path]
    else:
        cands = [os.path.join(os.getcwd(), user_path), os.path.join(root, user_path)]
    inside = False
    for c in cands:
        p = os.path.realpath(c)
        rel = os.path.relpath(p, root)
        if rel == ".." or rel.startswith("../") or os.path.isabs(rel):
            continue
        inside = True
        if os.path.exists(p):
            return rel
    if inside:
        die("%s %r does not exist" % (kind, user_path), code=2)
    die("%s %r is outside the repo root" % (kind, user_path), code=2)


def _ensure_home(home):
    os.makedirs(home, mode=0o700, exist_ok=True)
    info = os.lstat(home)
    if not stat.S_ISDIR(info.st_mode) or info.st_uid != os.getuid() or info.st_mode & 0o022:
        die("unsafe state directory: %s (must be owned, non-symlink and not group/world writable)" % home, code=2)


def _load_config(path):
    try:
        with open(path) as f:
            return yaml.safe_load(f)
    except (OSError, ValueError, yaml.YAMLError):
        # Parser exceptions can quote config contents (including auth_secret).
        die("cannot parse config: %s" % path, code=2)


def _validate_config(config, home, path):
    expected = os.path.join(home, "projects", "$projectFolderName")
    if (not isinstance(config, dict)
            or not isinstance(config.get("projects"), list)
            or config.get("trusted_project_path_patterns") != []
            or config.get("project_serena_folder_location") != expected):
        die("unsafe pilot config: %s (requires projects list, trusted_project_path_patterns: [], "
            "and project_serena_folder_location: %s; inspect and move the old config aside to reseed)"
            % (path, expected), code=2)


def _ensure_global_config(home, template):
    """Render the effective home once; validate safety-critical values on
    every call. Preserve Serena's normalized config, project list and secret.
    Unsafe old configs fail closed, never silently overwrite operator state."""
    dest = os.path.join(home, "serena_config.yml")
    if not os.path.lexists(dest):
        config = _load_config(template)
        if (not isinstance(config, dict) or config.get("project_serena_folder_location")
                != "@SERENA_HOME@/projects/$projectFolderName"):
            die("invalid pilot config template: %s" % template, code=2)
        config["project_serena_folder_location"] = os.path.join(home, "projects", "$projectFolderName")
        _validate_config(config, home, template)
        # Publish complete bytes without replacing a concurrent seeder's or
        # Serena's config. tempfile is private and link is atomic/no-clobber.
        with tempfile.NamedTemporaryFile(mode="w", dir=home) as tmp:
            yaml.safe_dump(config, tmp)
            tmp.flush()
            try:
                os.link(tmp.name, dest)
            except FileExistsError:
                pass
    info = os.lstat(dest)
    if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() or info.st_mode & 0o022:
        die("unsafe config file: %s" % dest, code=2)
    _validate_config(_load_config(dest), home, dest)


class _MCP:
    """Minimal stdio MCP client: one session, one tools/call. Adapted from
    the context-pack builder's client (build_pack.py, class MCP)."""

    def __init__(self, argv, env, cwd):
        self.p = subprocess.Popen(
            argv, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL, text=True, env=env, bufsize=1, cwd=cwd,
        )
        self._id = 0

    def _send(self, o):
        self.p.stdin.write(json.dumps(o) + "\n")
        self.p.stdin.flush()

    def _call(self, method, params):
        self._id += 1
        want = self._id
        self._send({"jsonrpc": "2.0", "id": want, "method": method, "params": params})
        while True:
            line = self.p.stdout.readline()
            if not line:
                raise RuntimeError("MCP server exited during %s" % method)
            try:
                o = json.loads(line)
            except ValueError:
                continue  # stdout must be JSON-RPC only; skip anything else
            if o.get("id") == want:
                if "error" in o:
                    raise RuntimeError(str(o["error"])[:500])
                return o["result"]

    def open(self):
        self._call("initialize", {
            "protocolVersion": MCP_PROTOCOL_VERSION,
            "capabilities": {},
            "clientInfo": {"name": "code-nav", "version": "1"},
        })
        self._send({"jsonrpc": "2.0", "method": "notifications/initialized"})

    def tool(self, name, args):
        return self._call("tools/call", {"name": name, "arguments": args})

    def close(self):
        p = self.p
        try:
            try:
                p.stdin.close()
            except BrokenPipeError:
                pass
            p.wait(timeout=10)
        except Exception:
            p.kill()
            p.wait()


def _child_env(home):
    env = dict(os.environ)
    # Lowercase "false": Serena's agent.py compares against exactly that.
    env["SERENA_USAGE_REPORTING"] = "false"
    env["SERENA_HOME"] = home
    # SolidLSP stores downloaded language servers in ~/.solidlsp. HOME is
    # /paperclip (world-writable) on this fleet, which must not hold tool
    # state -- same reason context-pack redirects HOME to /tmp.
    hov = env.get("HOME", "")
    if not hov or hov == "/paperclip" or hov.startswith("/paperclip/"):
        env["HOME"] = home
    return env


def _run_once(tool, args, timeout):
    opt = _opt_paths()
    if not os.path.exists(opt["serena_bin"]):
        die("serena not installed at %s (pilot install missing)" % opt["serena_bin"])
    if not os.path.exists(opt["context"]):
        die("context missing: %s (broken install)" % opt["context"])
    root = _repo_root()
    home = os.path.realpath(os.environ.get("SERENA_HOME") or "/tmp/serena-home")
    if (os.path.commonpath([home, root]) == root
            or home == "/paperclip" or home.startswith("/paperclip/") or "$" in home):
        die("SERENA_HOME must be outside the repo and /paperclip, with no $ placeholders", code=2)

    lock_dir = os.environ.get("CODE_NAV_LOCK_DIR") or "/tmp/code-nav-locks"
    _ensure_home(lock_dir)
    lock_path = os.path.join(lock_dir, hashlib.sha1(root.encode()).hexdigest() + ".lock")

    argv = [opt["serena_bin"]] + [
        opt["context"] if a == "@CONTEXT@" else a for a in SERENA_ARGV_TAIL
    ]
    env = _child_env(home)

    signal.signal(signal.SIGALRM, _on_alarm)
    signal.alarm(timeout)
    lock_fh = None
    mcp = None
    try:
        # One holder per repo root: concurrent calls queue instead of each
        # starting a 1.9 GB language server. The alarm bounds queue+call.
        lock_fh = open(lock_path, "a+b")
        fcntl.flock(lock_fh.fileno(), fcntl.LOCK_EX)
        _ensure_home(home)
        _ensure_global_config(home, opt["config_template"])
        # 2.0.0 falls back to repo/.serena when this directory is absent.
        # Create it before activation so repo project.yml is never loaded.
        _ensure_home(os.path.join(home, "projects"))
        _ensure_home(os.path.join(home, "projects", os.path.basename(root)))
        mcp = _MCP(argv, env, cwd=root)
        mcp.open()
        result = mcp.tool(tool, args)
    except _Timeout:
        die("timed out after %ds (another call may hold the repo lock, or the language server is still indexing)" % timeout, code=124)
    except RuntimeError as e:
        die("serena call failed: %s (server logs: %s)" % (e, os.path.join(home, "logs")), code=1)
    finally:
        signal.alarm(0)
        if mcp is not None:
            mcp.close()
        if lock_fh is not None:
            lock_fh.close()

    if result.get("isError"):
        text = "".join(
            c.get("text", "") for c in result.get("content", []) if c.get("type") == "text"
        ) or json.dumps(result)[:1000]
        die("serena tool error: %s" % text, code=1)
    texts = [c.get("text", "") for c in result.get("content", []) if c.get("type") == "text"]
    out = "".join(texts) if texts else json.dumps(result, indent=1)
    sys.stdout.write(out if out.endswith("\n") else out + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser(
        prog="code-nav",
        description="Serena-backed symbolic code navigation (Pilot B). Run from inside the repo.",
    )
    ap.add_argument("--timeout", type=int, default=DEFAULT_TIMEOUT_S,
                    help="bound in seconds for queue wait plus the tool call (default %(default)s)")
    sub = ap.add_subparsers(dest="cmd", required=True)

    p_out = sub.add_parser("outline", help="outline of symbols defined in a file")
    p_out.add_argument("file", help="file to outline (cwd-, repo-relative or absolute)")
    p_out.add_argument("--depth", type=int, default=1,
                       help="descendant depth: 0 = top-level only, 1 = plus immediate children like methods (default %(default)s)")

    p_sym = sub.add_parser("symbol", help="find symbols by name path, optionally with body")
    p_sym.add_argument("name_path", help="symbol name or path, e.g. MyClass/my_method")
    p_sym.add_argument("--body", action="store_true", help="include symbol source code")
    p_sym.add_argument("--in", dest="within", default="",
                       help="restrict search to this file or directory (much faster)")
    p_sym.add_argument("--depth", type=int, default=0, help="descendant depth (default %(default)s)")
    p_sym.add_argument("--info", action="store_true", help="include hover-like signature/doc info")

    p_ref = sub.add_parser("refs", help="exact references to a symbol (language server)")
    p_ref.add_argument("name_path", help="name path of the symbol")
    p_ref.add_argument("file", help="file containing the symbol")

    a = ap.parse_args(argv)
    if a.timeout <= 0:
        die("--timeout must be positive", code=2)

    if a.cmd == "outline":
        root = _repo_root()
        rel = _to_root_rel(root, a.file, kind="file")
        _run_once("get_symbols_overview", {"relative_path": rel, "depth": a.depth}, a.timeout)
    elif a.cmd == "symbol":
        root = _repo_root()
        within = _to_root_rel(root, a.within, kind="--in path") if a.within else ""
        _run_once("find_symbol", {
            "name_path_pattern": a.name_path,
            "depth": a.depth,
            "relative_path": within,
            "include_body": a.body,
            "include_info": a.info,
        }, a.timeout)
    elif a.cmd == "refs":
        root = _repo_root()
        rel = _to_root_rel(root, a.file, kind="file")
        _run_once("find_referencing_symbols", {"name_path": a.name_path, "relative_path": rel}, a.timeout)


if __name__ == "__main__":
    main()
