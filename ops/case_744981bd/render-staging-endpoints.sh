#!/usr/bin/env bash
# render-staging-endpoints.sh — stamp staging-app Gatus blocks (case_744981bd).
#
# Renders the Gatus fragment for the staging apps (two-web-next staging,
# two-bot-next staging, staging dashboard, staging redirect) as HTTP pull
# checks, plus TCP reachability checks for the staging backing stores, plus
# per-app external-endpoint blocks for the container-restart-loop signal
# (evaluated by ops/case_73259b15 coolify_restart_signal.sh with looser env
# overrides, pushed by the operator cron).
#
# Source-only: no network, no credentials, no Coolify, no Gatus. The operator
# pastes the output into the host gatus-config.yaml on the deploy card (no
# host deploy happens here). Deterministic: same input, byte-identical
# output — the suite enforces this against the checked-in example.
#
# Thresholds are deliberately LOOSER than the prod counterparts in
# ops/case_73259b15 (see README.md § Thresholds): staging flakes must not page.
# Concretely: 300s pull interval (vs 60s), 8000ms response budget (vs
# 3000ms), 30m restart heartbeat (vs 10m), and discord-only alerts (no
# custom/Akmatori pager — a red staging endpoint never opens an incident).
#
# Env (URLs are full health-check URLs, pasted host-side into the root-only
# 0600 env file; nothing live is committed — the committed output carries
# only ${VAR} references):
#   TWO_WEB_NEXT_STAGING_HEALTH_URL, TWO_BOT_NEXT_STAGING_HEALTH_URL,
#   TWO_STAGING_DASHBOARD_HEALTH_URL, TWO_STAGING_REDIRECT_HEALTH_URL
#     Rendered when set and non-empty; at least one app must be set.
#   STAGING_DB_TARGETS (optional)
#     Space-separated name=tcp://host:port pairs, e.g.
#     "staging-postgres=tcp://db.example.invalid:5432 staging-redis=tcp://db.example.invalid:6379".
#
# Usage: [APP_URLS...] [STAGING_DB_TARGETS="..."] render-staging-endpoints.sh \
#          > gatus-staging-apps.yaml
#
# Exit: 0 rendered to stdout · 2 refused (no app URL set, or a bad DB pair).
# Thresholds live in the emitted comments and in README.md (one place each).
set -uo pipefail

APPS=(
  "two-web-next:TWO_WEB_NEXT_STAGING_HEALTH_URL"
  "two-bot-next:TWO_BOT_NEXT_STAGING_HEALTH_URL"
  "dashboard:TWO_STAGING_DASHBOARD_HEALTH_URL"
  "redirect:TWO_STAGING_REDIRECT_HEALTH_URL"
)
DB_TARGETS="${STAGING_DB_TARGETS:-}"

# Thresholds (duplicated from README.md § Thresholds — keep both current):
# - HTTP pull checks: interval 300s, [STATUS] == 200, [RESPONSE_TIME] < 8000 —
#   5x the interval and ~2.6x the budget of the prod pull checks in
#   ops/case_73259b15, so staging flakes stay quiet.
# - TCP reachability: interval 300s, [CONNECTED] == true. A connected socket
#   proves a listener, not a healthy database — it notifies on "store
#   unreachable", never on "store slow".
# - Restart-loop external endpoints: heartbeat interval 30m (vs 10m prod). A
#   missed push still fails closed (UNKNOWN, never healthy) — Gatus-side.
# - Alerting is discord-only. The custom (Akmatori pager) alert present on
#   every prod block is deliberately ABSENT here: a red staging endpoint
#   must not page. The suite asserts this absence, with a mutant control.

declare -a RENDER_APPS=()
for pair in "${APPS[@]}"; do
  app="${pair%%:*}"
  var="${pair##*:}"
  if [[ -n "${!var:-}" ]]; then
    RENDER_APPS+=("$app:$var")
  fi
done
(( ${#RENDER_APPS[@]} > 0 )) \
  || { echo "render-staging-endpoints: refusing — at least one staging <APP>_HEALTH_URL must be set" >&2; exit 2; }

declare -a RENDER_DBS=()
if [[ -n "$DB_TARGETS" ]]; then
  read -r -a pairs <<<"$DB_TARGETS"
  for p in "${pairs[@]}"; do
    [[ "$p" =~ ^[A-Za-z0-9_.-]+\=tcp://[A-Za-z0-9_.-]+:[0-9]+$ ]] \
      || { echo "render-staging-endpoints: refusing — bad DB pair '$p' (want name=tcp://host:port)" >&2; exit 2; }
    RENDER_DBS+=("$p")
  done
fi

cat <<EOF
# GENERATED by ops/case_744981bd/render-staging-endpoints.sh — do not hand-edit.
# Paste the pull checks under the host gatus-config.yaml endpoints and the
# restart blocks under external-endpoints. Re-generate with the same env.
# Staging thresholds are looser than prod (300s pulls, 8000ms budget, 30m
# restart heartbeat) and alerts are discord-only: staging flakes must not
# page. Push side: one gatus_push per staging_staging-restart-<app> key
# per cron tick — the group-qualified key (group staging + endpoint name),
# which is what Gatus listens on at /api/v1/endpoints/<key>/external
# (verdict from ops/case_73259b15 coolify_restart_signal.sh with
# COOLIFY_RESTART_THRESHOLD=5 COOLIFY_RESTART_WINDOW_MIN=30; see README.md).
# That evaluator rides PR #551: until it lands on main, deploy the pull +
# TCP checks only and skip the restart pushes. A missed 30m restart
# heartbeat fails closed (UNKNOWN, never healthy).
EOF
for pair in "${RENDER_APPS[@]}"; do
  app="${pair%%:*}"
  var="${pair##*:}"
  cat <<EOF

  # HTTP health for staging app $app: 300s pull, 200 + <8000ms (looser than
  # the 60s/<3000ms prod budget in ops/case_73259b15). URL is operator-supplied.
  # Discord-only alert: staging flakes must not page.
  - name: staging-$app
    group: staging
    url: "\${$var}"
    interval: 300s
    conditions:
      - "[STATUS] == 200"
      - "[RESPONSE_TIME] < 8000"
    alerts:
      - type: discord
        description: "Staging app $app unhealthy (non-paging; see docs/runbooks/staging-app-health.md)"
EOF
done
for p in "${RENDER_DBS[@]:-}"; do
  [[ -n "$p" ]] || continue
  name="${p%%=*}"
  url="${p##*=}"
  cat <<EOF

  # TCP reachability for staging backing store $name ($url): 300s pull,
  # [CONNECTED] == true. Proves a listener, not a healthy database.
  # Discord-only alert: staging flakes must not page.
  - name: staging-db-$name
    group: staging
    url: "$url"
    interval: 300s
    conditions:
      - "[CONNECTED] == true"
    alerts:
      - type: discord
        description: "Staging backing store $name unreachable (non-paging; see docs/runbooks/staging-app-health.md)"
EOF
done
for pair in "${RENDER_APPS[@]}"; do
  app="${pair%%:*}"
  cat <<EOF

  # Container-restart-loop signal for staging $app: pushed by the operator
  # cron from ops/case_73259b15 coolify_restart_signal.sh (>=5 restarts in 30m,
  # or container not running, is UNHEALTHY — looser than the 3-per-15m prod
  # default). Heartbeat 30m — a missed push notifies, never pages.
  - name: staging-restart-$app
    group: staging
    token: "\${GATUS_EXTERNAL_TOKEN}"
    heartbeat:
      interval: 30m
    alerts:
      - type: discord
        description: "Staging app $app restart-loop or down (non-paging; see docs/runbooks/staging-app-health.md)"
EOF
done
