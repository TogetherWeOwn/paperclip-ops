#!/usr/bin/env bash
# render-garm-pool-endpoints.sh — stamp per-pool Gatus external-endpoint blocks.
#
# Gatus external endpoints are keyed per monitored thing, so per-pool liveness
# needs one block per GARM pool plus one per-label runner rollup block. Pool
# IDs are operator-known at deploy time (full UUIDs from `garm-cli pool list`;
# short prefixes are rejected by garm-cli, measured 2026-10-02), so this
# script renders the fragment from the same GARM_POOLS env the push script
# takes. Deterministic: same input, byte-identical output. Offline: no
# network, no credentials, no garm-cli — the operator pastes the output into
# the host Gatus config on the deploy card (no host deploy happens here).
#
# Usage: GARM_POOLS="<uuid> ..." [GARM_ELIGIBLE_LABEL=two-ephemeral] \
#          render-garm-pool-endpoints.sh > gatus-garm-pools.yaml
#
# Exit: 0 rendered to stdout · 2 refused (missing/bad GARM_POOLS or label).
# Thresholds live in the emitted comments and in README.md (one place each).
set -uo pipefail

ELIGIBLE_LABEL="${GARM_ELIGIBLE_LABEL:-two-ephemeral}"

[[ "$ELIGIBLE_LABEL" =~ ^[A-Za-z0-9_.-]+$ ]] \
  || { echo "render-garm-pool-endpoints: refusing — bad eligible label '$ELIGIBLE_LABEL'" >&2; exit 2; }
read -r -a POOLS <<<"${GARM_POOLS:-}"
(( ${#POOLS[@]} > 0 )) \
  || { echo "render-garm-pool-endpoints: refusing — GARM_POOLS (space-separated pool IDs) must be set" >&2; exit 2; }
for pool in "${POOLS[@]}"; do
  [[ "$pool" =~ ^[A-Za-z0-9_.-]+$ ]] \
    || { echo "render-garm-pool-endpoints: refusing — bad pool ID '$pool'" >&2; exit 2; }
done

# Thresholds (duplicated from README.md § Thresholds — keep both current):
# - heartbeat interval 10m per block: matches the aggregate platform_garm-pool
#   endpoint, so a missed per-pool push pages on the same clock. A missed
#   heartbeat fails closed (UNKNOWN, never healthy) — Gatus-side, no code.
# - alerting reuses the host config's discord+custom defaults (failure 3 /
#   success 2); nothing secret is emitted here — the token stays a ${ENV} ref.
cat <<EOF
# GENERATED by ops/case_b24794c2/render-garm-pool-endpoints.sh — do not hand-edit.
# Paste under the host gatus-config.yaml external-endpoints. Re-generate with:
#   GARM_POOLS="<uuid> ..." GARM_ELIGIBLE_LABEL=$ELIGIBLE_LABEL render-garm-pool-endpoints.sh
# Push side: one gatus_push per key per cron tick (see README.md wiring).
# A missed 10m heartbeat fails closed (UNKNOWN, never healthy).
EOF
for pool in "${POOLS[@]}"; do
  short="${pool:0:8}"
  cat <<EOF

  # Per-pool liveness for $short (pool $pool): enabled, presence-checked
  # min_idle_runners/max_runners/instances via garm_pool_health.sh (strict:
  # any absent field is UNHEALTHY), over-max, warm-capacity and prov-fail
  # rules per README.md. Heartbeat 10m — a missed push pages.
  - name: garm-pool-$short
    group: platform
    token: "\${GATUS_EXTERNAL_TOKEN}"
    heartbeat:
      interval: 10m
    alerts:
      - type: discord
        description: "GARM pool $short unhealthy (see per-pool push log)"
      - type: custom
        description: "GARM pool $short unhealthy (see per-pool push log)"
EOF
done
cat <<EOF

  # Per-label runner rollup for label $ELIGIBLE_LABEL: online (idle+busy) vs
  # provision-fail/stale counts across all pools serving the label, evaluated
  # with --waiting when eligible demand is queued. Heartbeat 10m.
  - name: garm-runners-$ELIGIBLE_LABEL
    group: platform
    token: "\${GATUS_EXTERNAL_TOKEN}"
    heartbeat:
      interval: 10m
    alerts:
      - type: discord
        description: "GARM runners for label $ELIGIBLE_LABEL unhealthy (see rollup push log)"
      - type: custom
        description: "GARM runners for label $ELIGIBLE_LABEL unhealthy (see rollup push log)"
EOF
