"""Bounded, probe-free documentation views of the verify-fast inventory."""

import hashlib
import html
import json
import re
import sys

MAX_BYTES = 256 * 1024
MAX_SUITES = 256
ID = re.compile(r"[a-z0-9][a-z0-9._-]*\Z")


def nonempty(value):
    return isinstance(value, str) and bool(value.strip())


def string_list(value):
    return isinstance(value, list) and all(nonempty(item) for item in value)


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate JSON key")
        result[key] = value
    return result


def read_bounded(path):
    with path.open("rb") as source:
        value = source.read(MAX_BYTES + 1)
    if len(value) > MAX_BYTES:
        raise ValueError("size_limit: input exceeds 256 KiB; reduce the inventory/artifact")
    return value


def reject_constant(value):
    raise ValueError("invalid_inventory: non-finite JSON numbers are not supported")


def load_registry(path):
    data = json.loads(read_bounded(path), object_pairs_hook=unique_object,
                      parse_constant=reject_constant)
    if not isinstance(data, dict) or type(data.get("schema_version")) is not int or data["schema_version"] != 1:
        raise ValueError("invalid_inventory: require schema_version 1")
    catalog, suites = data.get("prerequisite_catalog"), data.get("suites")
    if not isinstance(catalog, dict) or not isinstance(suites, list) or not 0 < len(suites) <= MAX_SUITES:
        raise ValueError("invalid_inventory: require a prerequisite catalog and 1..256 suites")
    for name, spec in catalog.items():
        if not nonempty(name) or not isinstance(spec, dict) or not isinstance(spec.get("probe"), dict):
            raise ValueError("invalid_inventory: invalid prerequisite definition")
        probe = spec["probe"]
        if not ((set(probe) == {"which"} and nonempty(probe["which"])) or
                (set(probe) == {"argv"} and string_list(probe["argv"]) and probe["argv"])):
            raise ValueError("invalid_inventory: prerequisite probe needs which or nonempty argv")
    seen = set()
    for entry in suites:
        if not isinstance(entry, dict):
            raise ValueError("invalid_inventory: suite must be an object")
        identifier = entry.get("id")
        if not isinstance(identifier, str) or not ID.fullmatch(identifier) or identifier in seen:
            raise ValueError("invalid_inventory: suite ids must be valid and unique")
        seen.add(identifier)
        command, names, prep = entry.get("command"), entry.get("prerequisites"), entry.get("preparation")
        if entry.get("tier") not in ("parse", "fast") or not (
                nonempty(command) or (string_list(command) and command)):
            raise ValueError("invalid_inventory: suite needs a tier and nonempty command")
        if not string_list(names) or len(names) != len(set(names)) or any(name not in catalog for name in names):
            raise ValueError("invalid_inventory: suite prerequisites must reference the catalog once each")
        if not isinstance(prep, dict) or not string_list(prep.get("actions")):
            raise ValueError("invalid_inventory: preparation.actions must be a string list")
        if "description" in entry and not nonempty(entry["description"]):
            raise ValueError("invalid_inventory: description must be nonempty text")
    return data


def build_registry(inventory, script_dir):
    """Hash contracts and their renderers, never environment-dependent readiness."""
    contract = {key: value for key, value in inventory.items() if key != "_maintainer_note"}
    digest = hashlib.sha256()
    digest.update(json.dumps(contract, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode())
    for name in ("verify-fast-plan.py", "verify-fast.sh", "verify_fast_registry.py"):
        digest.update(b"\0" + name.encode() + b"\0" + read_bounded(script_dir / name))
    suites = []
    for entry in inventory["suites"]:
        suite = dict(entry)
        suite.setdefault("description", f"Run {entry['id']} verification checks.")
        suites.append(suite)
    return {
        "schema_version": 1,
        "registry_revision": "sha256:" + digest.hexdigest(),
        "complete": True,
        "total": len(suites),
        "limit": MAX_SUITES,
        "prerequisite_catalog": inventory["prerequisite_catalog"],
        "suites": suites,
    }


def render_docs(registry):
    lines = [
        "# Verification tool registry", "",
        "Generated from `scripts/verify-fast-inventory.json`; do not edit this file.", "",
        f"Registry revision: `{registry['registry_revision']}`", "",
        f"Schema: 1. Complete: true. Suites: {registry['total']}. Limit: {MAX_SUITES}.", "",
        "## Use and verification", "",
        "Use this catalog to choose an offline verification command. It describes the",
        "existing verify-fast suite boundary, not every operator or plugin capability.",
        "Descriptions, commands, prerequisites and preparation come from one inventory.",
        "Commands may be shell expressions or verify-fast functions, not standalone argv.",
        "Listing docs never executes commands or prerequisite probes. Normal verification",
        "may prepare the checkout; discovery does not authorize host operations.", "",
        "```sh", "bash scripts/verify-fast.sh --registry",
        "bash scripts/verify-fast.sh --docs", "bash scripts/verify-fast.sh --check-docs",
        "bash scripts/verify-fast.sh --plan --json", "```", "",
        "`--registry` emits the complete JSON view. Cache by `registry_revision`, not",
        "`schema_version`: inventory contracts or renderer/wrapper source changes invalidate",
        "both derived files. Whitespace and the maintainer note are not contract changes.",
        "For a pinned revision use `python3 scripts/verify-fast-plan.py",
        "--emit-registry-json --expect-revision sha256:<digest>`; mismatch refuses without",
        "partial output. Legacy plan/list shapes are unchanged; plan readiness is dynamic.", "",
        "Input and each output are limited to 256 KiB; at most 256 suites are supported.",
        "Overflow or malformed inventory refuses instead of truncating a complete result.",
        "No filtered registry is served. For a smaller dynamic plan use `--plan --parse-only`.", "",
        "Regenerate both views explicitly after a source change, then run the CI check:", "",
        "```sh", "bash scripts/verify-fast.sh --registry > docs/verify-fast-registry.json",
        "bash scripts/verify-fast.sh --docs > docs/verify-fast-registry.md",
        "bash scripts/verify-fast.sh --check-docs", "```", "",
        "The check is read-only and byte-exact for both files. It exits 1 for missing or",
        "stale docs, 2 for invalid usage/input or bounds, and 0 on success. Regenerate on",
        "staleness; fix the inventory or reduce its size on validation failure. This is",
        "repo CI tooling, not an installed host job or a runtime discovery service.", "",
        "## Suites", "",
    ]
    for suite in registry["suites"]:
        command = suite["command"]
        if isinstance(command, list):
            command = json.dumps(command, ensure_ascii=True)
        # HTML escaping prevents metadata from closing its own code block or
        # injecting active markup into generated documentation.
        lines += [f"### {suite['id']}", "", html.escape(suite["description"]), "",
                  f"Tier: {suite['tier']}. Prerequisites: " +
                  html.escape(", ".join(suite["prerequisites"]) or "none") + ".", "",
                  "<pre>" + html.escape(command) + "</pre>", "",
                  "Preparation: " + html.escape("; ".join(suite["preparation"]["actions"]) or "none") + ".", ""]
    return "\n".join(lines)


def registry_views(inventory_path, script_dir):
    registry = build_registry(load_registry(inventory_path), script_dir)
    views = {
        "verify-fast-registry.json": json.dumps(registry, indent=2, ensure_ascii=True) + "\n",
        "verify-fast-registry.md": render_docs(registry),
    }
    if any(len(text.encode("utf-8")) > MAX_BYTES for text in views.values()):
        raise ValueError("size_limit: derived output exceeds 256 KiB; reduce the inventory")
    return registry, views


def report_error(code, message, next_action):
    print(json.dumps({"code": code, "message": message, "retryable": False,
                      "next_action": next_action}), file=sys.stderr)


def run(mode, inventory_path, script_dir, expected_revision=None):
    try:
        registry, views = registry_views(inventory_path, script_dir)
        if expected_revision is not None and expected_revision != registry["registry_revision"]:
            raise ValueError("stale_revision: refresh the registry and rebuild derived indexes")
        if mode == "--check-docs":
            root = inventory_path.resolve().parent
            if root.name == "scripts":
                root = root.parent
            for name, text in views.items():
                try:
                    current = read_bounded(root / "docs" / name)
                except FileNotFoundError:
                    current = None
                if current != text.encode("utf-8"):
                    report_error("stale_docs", "Generated registry documentation is missing or stale.",
                                 "Regenerate both views with --registry > docs/verify-fast-registry.json "
                                 "and --docs > docs/verify-fast-registry.md; rerun --check-docs.")
                    return 1
            return 0
        name = "verify-fast-registry.json" if mode == "--emit-registry-json" else "verify-fast-registry.md"
        print(views[name], end="")
        return 0
    except (OSError, ValueError, UnicodeError, RecursionError) as exc:
        message = str(exc)[:512]
        code = message.partition(":")[0]
        if code not in ("invalid_inventory", "size_limit", "stale_revision"):
            code = "invalid_inventory" if isinstance(exc, ValueError) else "registry_io_error"
        report_error(code, message, "Fix the inventory/input bounds or refresh the pinned revision; "
                     "regenerate derived docs and rerun --check-docs.")
        return 2
