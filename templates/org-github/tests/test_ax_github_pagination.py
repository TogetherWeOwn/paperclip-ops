def paginated_fixture(search_pages, pr_evidence, cost_tokens=1000,
                      cost_evidence=None, issues=None):
    """Fixture row with raw evidence plus diverging legacy values."""
    if cost_evidence is None:
        cost_evidence = cost_evidence_matching(cost_tokens)
    if issues is None:
        issues = issues_two_touched_one_blocked()
    row = {"repo": "Example/a", "merged_prs": LEGACY_MERGED,
           "truncated": False, "first_commit_states": list(LEGACY_STATES),
           "search_pages": search_pages, "pr_evidence": pr_evidence}
    return {"github_rows": [row], "cost_tokens": cost_tokens,
            "cost_evidence": cost_evidence, "issues": issues,
            "window_start": REPORT_WINDOW_START}


def run_main(args):
    out, err = io.StringIO(), io.StringIO()
    try:
        with redirect_stdout(out), redirect_stderr(err):
            code = ax_metrics.main(args)
    except SystemExit as exc:
        code = exc.code
    text = out.getvalue()
    report = None
    if text.strip():
        try:
            report = json.loads(text)
        except ValueError:
            report = None
    return code, report, text, err.getvalue()


def run_from_file(fixture, days=REPORT_DAYS, extra_args=()):
    with tempfile.NamedTemporaryFile(
            "w", suffix=".json", delete=False) as fh:
        json.dump(fixture, fh)
        path = fh.name
    try:
        return run_main(["--from-file", path, "--days", str(days),
                         *extra_args])
    finally:
        os.unlink(path)


def get_help_text():
    _code, _report, text, err = run_main(["--help"])
    return text + err


def assert_machine_readable(testcase, metric, name):
    for legacy in ("value", "definition", "provenance"):
        testcase.assertIn(
            legacy, metric, f"{name} lost legacy key {legacy}")
    for key in ("validity", "reason_code", "reason", "next_action",
                "completeness", "source_window", "numerator",
                "denominator", "numerator_source",
                "denominator_source"):
        testcase.assertIn(key, metric, f"{name} missing {key}")
    testcase.assertIn(
        metric["validity"], VALIDITY_ENUM, f"{name} validity enum")
    testcase.assertIn(
        metric["completeness"], COMPLETENESS_ENUM,
        f"{name} completeness enum")
    testcase.assertIsInstance(metric["reason_code"], str)
    testcase.assertTrue(
        re.fullmatch(r"[a-z0-9_]+", metric["reason_code"] or ""),
        f"{name} reason_code must be snake_case, "
        f"got {metric['reason_code']!r}")
    testcase.assertIsInstance(metric["numerator_source"], str)
    testcase.assertTrue(
        metric["numerator_source"].strip(),
        f"{name} numerator_source empty")
    testcase.assertIsInstance(metric["denominator_source"], str)
    testcase.assertTrue(
        metric["denominator_source"].strip(),
        f"{name} denominator_source empty")
    if metric["source_window"] is not None:
        testcase.assertIsInstance(metric["source_window"], dict)
    if metric["validity"] != "valid":
        testcase.assertTrue(
            str(metric["reason"]).strip(), f"{name} reason empty")
        testcase.assertTrue(
            str(metric["next_action"]).strip(),
            f"{name} next_action empty")
    else:
        testcase.assertEqual(
            metric["reason_code"], "ok", f"{name} valid must use ok")


def assert_sampled_counts(testcase, metric, sampled, known, pending,
                          unknown):
    testcase.assertIn("counts", metric,
                      "green metric must carry sampled counts")
    counts = metric["counts"]
    testcase.assertIsInstance(counts, dict)
    for key, want in (("sampled", sampled), ("known", known),
                      ("pending", pending), ("unknown", unknown)):
        testcase.assertIn(key, counts, f"counts missing {key}")
        testcase.assertEqual(counts[key], want,
                             f"counts.{key} want {want}, "
                             f"got {counts[key]!r}")
    testcase.assertEqual(
        known + pending + unknown, sampled,
        "sampled must equal known+pending+unknown")


def assert_search_withheld(testcase, report, merged_total,
                           tokens_num=1000):
    testcase.assertEqual(report["merged_prs_total"], merged_total)
    green = report["metrics"]["first_push_green_rate"]
    tokens = report["metrics"]["tokens_per_merged_pr"]
    for metric, name in ((green, "first_push_green_rate"),
                         (tokens, "tokens_per_merged_pr")):
        assert_machine_readable(testcase, metric, name)
        testcase.assertIsNone(
            metric["value"], f"{name} must withhold on refused search")
        testcase.assertEqual(
            metric["validity"], "withheld", f"{name} validity")
        testcase.assertIn(
            metric["reason_code"], SEARCH_CODES,
            f"{name} reason_code, got {metric['reason_code']!r}")
    testcase.assertEqual(green["numerator"], 0)
    testcase.assertEqual(green["denominator"], 0)
    assert_sampled_counts(testcase, green, 0, 0, 0, 0)
    testcase.assertEqual(tokens["numerator"], tokens_num)
    testcase.assertEqual(tokens["denominator"], merged_total)
    esc = report["metrics"]["escalations_per_100_cards"]
    assert_machine_readable(
        testcase, esc, "escalations_per_100_cards")
    testcase.assertEqual(esc["validity"], "valid")
    testcase.assertAlmostEqual(esc["value"], 50.0)


