#!/usr/bin/env python3
"""Immutable acceptance: paginated GitHub reads, refuse incomplete results.

Do not edit this file. The builder starts from the pushed test branch and
never edits this file. All fixtures are synthetic; no network, credentials,
or production access. Deterministic bounds; machine-output assertions only.

Runnable command (existing dependencies only, no installs):

  python3 -B -m unittest discover -s templates/org-github/tests \
      -p 'test_ax_*py'

Contract under test (builder implements in ax_metrics.py + help text):

* Every github row in a --from-file fixture MAY carry raw paginated
  evidence alongside the legacy keys:
    "search_pages": [page, ...] where a page is
      {"items": [{"number": N, "closed_at": iso}...],
       "total_count": int, "incomplete_results": bool}
    or null for a failed page. "pr_evidence": [{"number": N,
    "status": {"state":..., "total_count":...}?,
    "check_run_pages": [checkpage...]?}...] where a check page is
      {"total_count": int, "check_runs": [{"conclusion":...,
       "status":...}...]}
    or null, or {"error": str}, for a failed page.
  When "search_pages" is present the builder consumes it (in order,
  within the explicit bounds below) and IGNORES the legacy merged_prs /
  first_commit_states / truncated keys on that row. Every fixture here
  carries diverging legacy values (merged_prs 99, states ["success"]) so
  a builder that ignores the raw evidence fails.
* Bounds (explicit module constants, builder MUST define):
    MAX_SEARCH_PAGES int in [2, 5]
    MAX_SEARCH_ITEMS int in [1, 500]
    MAX_CHECK_RUN_PAGES int in [2, 20]
  Search pages beyond MAX_SEARCH_PAGES, or search items beyond
  MAX_SEARCH_ITEMS, withhold the GitHub ratios (bound hit). Check-run
  pages beyond MAX_CHECK_RUN_PAGES degrade that PR's state to unknown.
* Refusal table (exit 0, ratios withheld with a coded reason):
    - any search page with incomplete_results true -> first_push_green_rate
      AND tokens_per_merged_pr are None, reason_code in SEARCH_CODES.
    - search pages/items beyond the bound -> same refusal with a
      bound-flavoured reason (bound/cap/limit/exceed in the reason).
    - on search refusal no first-commit states are evaluated:
      green counts are all zero, numerator/denominator 0/0; tokens keeps
      its cost numerator with denominator == merged_prs_total; the
      unrelated escalations metric stays valid.
    - merged_prs_total on any completed-or-refused search is the search
      total_count (legacy population semantics preserved); the refusal
      applies to the RATIOS, never silently to a truncated sample.
* Check-run reconciliation per PR (exit 0, degrade, never fail the run):
    - check_run_pages present: concatenate runs in page order; the read
      is reconciled only when every page succeeded, page count is within
      MAX_CHECK_RUN_PAGES, every page carries total_count, and fetched
      runs == total_count. Anything else -> that PR is "unknown".
    - check_run_pages omitted + status present -> state from the legacy
      status alone (nothing to reconcile). Omitted + omitted, a bare
      {"number": N} entry, or a searched PR with no pr_evidence entry
      at all -> unknown. pr_evidence for a PR absent from the search
      sample is ignored.
    - reconciled runs merge with the legacy status under the EXISTING
      combine_commit_state semantics (failure wins, unanimous success,
      pending votes survive, no evidence -> unknown).
    - unknown PRs are excluded from the green ratio (never counted as
      success) and counted under counts.unknown. Pending PRs are
      excluded from known and counted under counts.pending. All-unknown
      (or pending-only) samples withhold green with an UNKNOWN_CODES
      reason, never success-by-omission. Check-level unknowns never
      withhold tokens_per_merged_pr (the search population is intact).
* Counts: first_push_green_rate ALWAYS carries counts with int keys
  sampled/known/pending/unknown, where sampled == known + pending +
  unknown (sampled counts every consumed sample PR, including unknowns).
* Empty search (no items, total_count 0) withholds green and (verified
  window) tokens with zero-denominator codes. A null (failed) search
  page fails the run with exit 1 and names github on stderr (legacy
  fetch-failure rule preserved). Withheld/degraded reports exit 0.
  Unknown flags and --days 0 refuse with exit 2.
* Legacy rows without search_pages behave EXACTLY as before; cost-window
  verification, Paperclip-scan truncation semantics, the weekly private
  workflow shape and SCHEMA_VERSION compat rules are unchanged
  (schema_version stays an int >= 2; bump only if breaking).
* Offline: --from-file drives every case; replay makes zero network
  calls, reads zero credentials, and is byte-deterministic.
* --help documents incomplete_results, pagination, the bounds, and the
  sampled counts, alongside the existing window-verification docs.

Reason-code allowlists (builder picks the most specific; tests accept the
set so the builder can be precise without breaking the contract):
"""

