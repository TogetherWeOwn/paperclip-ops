class OverBoundSearchTest(unittest.TestCase):
    def test_page_bound_hit_withholds(self):
        bound = search_bound_pages()
        self.assertIsInstance(bound, int, "MAX_SEARCH_PAGES required")
        numbers = list(range(101, 101 + 2 * (bound + 1)))
        pages = []
        for start in range(0, len(numbers), 2):
            pages.append(search_page(numbers[start:start + 2],
                                     total=len(numbers)))
        self.assertEqual(len(pages), bound + 1)
        fixture = paginated_fixture(
            pages, [pr(n, status=status_only("success"))
                    for n in numbers])
        code, report, _text, _err = run_from_file(fixture)
        self.assertEqual(code, 0)
        assert_search_withheld(self, report, len(numbers))
        reason = str(report["metrics"]["first_push_green_rate"][
            "reason"]).lower()
        self.assertTrue(
            any(word in reason
                for word in ("bound", "cap", "limit", "exceed")),
            f"bound refusal must name the bound, got {reason!r}")

    def test_item_bound_hit_withholds(self):
        bound = search_bound_items()
        self.assertIsInstance(bound, int, "MAX_SEARCH_ITEMS required")
        total = bound + 1
        numbers = list(range(1000, 1000 + total))
        cut = total // 2
        pages = [search_page(numbers[:cut], total=total),
                 search_page(numbers[cut:], total=total)]
        fixture = paginated_fixture(
            pages, [pr(n, status=status_only("success"))
                    for n in numbers])
        code, report, _text, _err = run_from_file(fixture)
        self.assertEqual(code, 0)
        assert_search_withheld(self, report, total)


