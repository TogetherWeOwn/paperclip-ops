def run_from_file(fixture, days=REPORT_DAYS):
    with tempfile.NamedTemporaryFile(
            "w", suffix=".json", delete=False) as fh:
        json.dump(fixture, fh)
        path = fh.name
    try:
        buf = io.StringIO()
        with redirect_stdout(buf):
            code = ax_metrics.main(
                ["--from-file", path, "--days", str(days)])
        text = buf.getvalue()
        report = json.loads(text) if code == 0 else None
        return code, report, text
    finally:
        os.unlink(path)


def get_help_text():
    buf_out = io.StringIO()
    buf_err = io.StringIO()
    try:
        with redirect_stdout(buf_out), redirect_stderr(buf_err):
            ax_metrics.main(["--help"])
    except SystemExit as exc:
        if exc.code != 0:
            raise AssertionError(
                f"--help exited {exc.code}: {buf_err.getvalue()!r}")
    return buf_out.getvalue() + buf_err.getvalue()


def assert_machine_readable(testcase, metric, name):
    for legacy in ("value", "definition", "provenance"):
        testcase.assertIn(
            legacy, metric, f"{name} lost legacy key {legacy}")
    for key in ("validity", "reason_code", "reason", "next_action",
                "completeness", "source_window", "numerator",
                "denominator", "numerator_source",
                "denominator_source"):
        testcase.assertIn(key, metric, f"{name} missing {key}")
    testcase.assertIn(
        metric["validity"], VALIDITY_ENUM, f"{name} validity enum")
    testcase.assertIn(
        metric["completeness"], COMPLETENESS_ENUM,
        f"{name} completeness enum")
    testcase.assertIsInstance(metric["reason_code"], str)
    testcase.assertTrue(
        re.fullmatch(r"[a-z0-9_]+", metric["reason_code"] or ""),
        f"{name} reason_code must be snake_case, "
        f"got {metric['reason_code']!r}")
    testcase.assertIsInstance(metric["numerator_source"], str)
    testcase.assertTrue(
        metric["numerator_source"].strip(),
        f"{name} numerator_source empty")
    testcase.assertIsInstance(metric["denominator_source"], str)
    testcase.assertTrue(
        metric["denominator_source"].strip(),
        f"{name} denominator_source empty")
    if metric["source_window"] is not None:
        testcase.assertIsInstance(metric["source_window"], dict)
    if metric["validity"] != "valid":
        testcase.assertTrue(
            str(metric["reason"]).strip(), f"{name} reason empty")
        testcase.assertTrue(
            str(metric["next_action"]).strip(),
            f"{name} next_action empty")
    else:
        testcase.assertEqual(
            metric["reason_code"], "ok", f"{name} valid must use ok")


def assert_window_withheld(testcase, metric):
    assert_machine_readable(testcase, metric, "tokens_per_merged_pr")
    testcase.assertIsNone(
        metric["value"], "unverified window must withhold value")
    testcase.assertIn(
        metric["validity"], {"withheld", "unavailable"},
        "unverified window validity")
    testcase.assertIn(
        metric["reason_code"], WINDOW_CODES,
        f"unverified window reason_code, got {metric['reason_code']!r}")
    combined = (str(metric["reason"]) + " "
                + str(metric["next_action"])).lower()
    testcase.assertTrue(
        ("window" in combined) or ("period" in combined),
        "window reason must name window/period with action")
    testcase.assertTrue(
        any(token in combined for token in
            ("evidence", "window", "period", "date", "range",
             "verify", "match", "provide", "narrow", "widen")),
        "window reason must carry a next action")


