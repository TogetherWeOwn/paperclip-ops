#!/usr/bin/env python3
"""Immutable acceptance: withhold unverified-window and partial ratios.

Do not edit this file. The builder starts from the pushed test branch and
never edits this file. All fixtures are synthetic; no network, credentials,
or production access. Deterministic bounds; machine-output assertions only.

Runnable command (existing dependencies only, no installs):

  python3 -B -m unittest discover -s templates/org-github/tests -p 'test_ax_*py'

Contract under test (builder implements in ax_metrics.py + help text):

* Report keeps every legacy top-level key (tool, window_days, window_start,
  repos, merged_prs_total, issues_truncated, metrics) and every legacy
  per-metric key (value, definition, provenance). It adds schema_version
  (int) and window_end (ISO8601) at top level. schema_version bumps when
  legacy value semantics change (bare totals no longer yield ratios).
* Every metric adds machine-readable fields; no prose scraping:
  validity in {valid, withheld, partial, unavailable},
  reason_code stable snake_case (ok when valid),
  reason human actionable non-empty when not valid,
  next_action actionable non-empty when not valid,
  completeness in {complete, partial, unknown},
  source_window dict {start, end, days} or None (key always present),
  numerator / denominator numbers or None (keys always present),
  numerator_source / denominator_source non-empty strings,
  counts dict with integer counts when completeness is partial.
* tokens_per_merged_pr is valid only when cost evidence carries an explicit
  window_start/window_end demonstrably matching the report window
  (same dates). Missing, mismatching, or unsupported period evidence
  (bare total, all-time, unknown, monthly vs weekly, last-90-days, etc.)
  returns value None with validity withheld/unavailable and reason_code in
  WINDOW_CODES. Never invent cost API query params; never infer weekly
  semantics from a bare total.
* Fixture keys: builder MUST support legacy cost_tokens (bare total) plus
  new cost_evidence {tokens, window_start, window_end, period?, source?}.
  Legacy bare total alone withholds (it has no verifiable window).
  cost_evidence with matching window validates; mismatching/unsupported
  withholds even when cost_tokens is present.
* escalations_per_100_cards from a capped, failed, or incomplete scan must
  never be valid+complete with an ordinary value. Return value None with
  scan reason_code, or a partial/sample-qualified value with validity
  partial, completeness partial, counts, and next_action. Complete scans
  stay valid; empty windows withhold with no-evidence codes, not partial.
  Unrelated valid metrics stay available when one metric withholds.
* Retain bounded pagination/timeouts, optional-credential degradation
  (credentials_missing, not a crash), and offline --from-file replay.
  Identical fixture input produces byte-identical stdout. Offline replay
  makes zero network calls, reads zero credentials, and performs zero
  board mutations. Report never echoes credential values.
* --help documents window verification, reason codes, a concise JSON
  schema example with the new fields, and the offline discovery command
  (unittest discover -p test_ax_*). The weekly private workflow stays
  weekly+dispatch only (never activated to push), cost/card values stay
  out of the summary.

Reason-code allowlists (builder picks the most specific; tests accept the
set so the builder can be precise without breaking the contract):
"""

