class LiveCostAdapterTest(unittest.TestCase):
    def setUp(self):
        self.tmp_env = {
            "gh": "TEST_SYNTHETIC_GH_TOKEN_XW",
            "url": "TEST_SYNTHETIC_PC_URL_XW",
            "key": "TEST_SYNTHETIC_PC_KEY_XW",
            "company": "TEST_SYNTHETIC_PC_COMPANY_XW",
        }
        clear_synthetic_env(self.tmp_env)
        self.saved = {
            "merged": ax_metrics.fetch_merged_prs,
            "state": ax_metrics.fetch_first_commit_state,
            "pcget": ax_metrics.paperclip_get,
            "issues": ax_metrics.fetch_paperclip_issues,
        }
        ax_metrics.fetch_merged_prs = lambda repo, since, token: (
            [{"number": 1, "merged_at": REPORT_WINDOW_END},
             {"number": 2, "merged_at": REPORT_WINDOW_END}],
            False, 2)
        states = iter(["success", "failure"])

        def fake_state(repo, number, token):
            try:
                return next(states)
            except StopIteration:
                return "success"

        ax_metrics.fetch_first_commit_state = fake_state
        ax_metrics.fetch_paperclip_issues = lambda base, key, company: (
            issues_two_touched_one_blocked(), False, None)

    def tearDown(self):
        ax_metrics.fetch_merged_prs = self.saved["merged"]
        ax_metrics.fetch_first_commit_state = self.saved["state"]
        ax_metrics.paperclip_get = self.saved["pcget"]
        ax_metrics.fetch_paperclip_issues = self.saved["issues"]
        clear_synthetic_env(self.tmp_env)

    def collect(self, cost_payload, seen_paths=None):
        set_synthetic_env(self.tmp_env)

        def fake_get(base_url, api_key, path):
            if seen_paths is not None:
                seen_paths.append(path)
            if path.endswith("/costs/summary"):
                return dict(cost_payload), None
            raise AssertionError(f"unexpected live path {path}")

        ax_metrics.paperclip_get = fake_get
        args = make_live_args(self.tmp_env)
        return ax_metrics.collect_live(args, REPORT_WINDOW_START)

    def test_live_matching_period_yields_valid(self):
        cost = {"totalTokens": 1000,
                "window_start": REPORT_WINDOW_START,
                "window_end": REPORT_WINDOW_END}
        report = self.collect(cost)
        metric = report["metrics"]["tokens_per_merged_pr"]
        assert_machine_readable(self, metric, "tokens_per_merged_pr")
        self.assertEqual(metric["validity"], "valid")
        self.assertAlmostEqual(metric["value"], 500.0)

    def test_live_mismatching_period_withholds(self):
        cost = {"totalTokens": 1000,
                "window_start": "2026-10-01T00:00:00Z",
                "window_end": "2026-10-08T00:00:00Z"}
        report = self.collect(cost)
        assert_window_withheld(
            self, report["metrics"]["tokens_per_merged_pr"])

    def test_live_bare_total_without_period_withholds(self):
        report = self.collect({"totalTokens": 1000})
        assert_window_withheld(
            self, report["metrics"]["tokens_per_merged_pr"])

    def test_live_unsupported_period_withholds(self):
        for period in ("all-time", "unknown", "monthly"):
            with self.subTest(period=period):
                report = self.collect(
                    {"totalTokens": 1000, "period": period})
                assert_window_withheld(
                    self, report["metrics"]["tokens_per_merged_pr"])

    def test_live_cost_request_invents_no_query_params(self):
        seen = []
        cost = {"totalTokens": 1000,
                "window_start": REPORT_WINDOW_START,
                "window_end": REPORT_WINDOW_END}
        self.collect(cost, seen_paths=seen)
        self.assertTrue(seen)
        for path in seen:
            if "costs/summary" in path:
                self.assertNotIn("?", path)
                lowered = path.lower()
                for invented in ("window", "period", "start", "end",
                                 "days", "from", "to", "range"):
                    self.assertNotIn(
                        invented, lowered,
                        f"cost path must not invent {invented}: {path}")


